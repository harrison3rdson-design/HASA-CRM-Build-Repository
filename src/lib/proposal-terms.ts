export const MAX_PROPOSAL_TERMS_LENGTH = 50_000;

export function resolveDefaultProposalTerms(value: unknown): string {
  const terms = String(value ?? "").trim();
  return terms || STANDARD_PROPOSAL_TERMS;
}

export function parseProposalTerms(value: unknown): string {
  const terms = String(value ?? "").trim();
  if (!terms) throw new Error("Proposal terms and conditions are required.");
  if (terms.length > MAX_PROPOSAL_TERMS_LENGTH) {
    throw new Error("Proposal terms and conditions cannot exceed 50,000 characters.");
  }
  return terms;
}
